package com.lvsmsmch.aichat._common

/**
 * Палитра цветов аватарок. Цвет выдаётся ОДИН раз при создании юзера/персонажа/чата
 * и дальше статичен для всех клиентов.
 *
 * Убраны: #A6635C, #5C6BC0, #815CA6 — не нравились в интерфейсе.
 * Холодные сине-зелёные смягчены: чистая бирюза и «кислотный» зелёный читались
 * ядовито на тёмном фоне.
 */
object AvatarColors {
    val palette = listOf(
        "#7C5CBF", "#4A6FA5", "#8C7A42", "#A05744", "#96455E",
        "#B07D3C", "#5E5CA6", "#4E8E6B", "#4F8F86", "#58876C",
        "#58838C", "#7E9160",
    )
    fun random(): String = palette.random()
}
