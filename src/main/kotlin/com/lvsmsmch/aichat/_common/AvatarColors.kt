package com.lvsmsmch.aichat._common

/**
 * Палитра цветов аватарок. Цвет выдаётся ОДИН раз при создании юзера/персонажа/чата
 * и дальше статичен для всех клиентов.
 *
 * История: убраны оранжевые/дублирующиеся тона, остальные усилены на ~20%
 * насыщенности; голубой сдвинут в сторону синего. Затем убраны зелёные
 * (#418E64, #7A9156) — зелёный в приложении означает акцент, и зелёная
 * аватарка читалась как элемент интерфейса; на их места встали петроль и
 * пурпур. Клиент дублирует этот список в `AvatarPalette` — правим оба.
 */
object AvatarColors {
    val palette = listOf(
        "#6F48BF", "#3864A5", "#8C7633", "#A04832", "#963553",
        "#504DA6", "#4E6B8C", "#2E6F8C", "#7E3F8C",
    )
    fun random(): String = palette.random()
}
